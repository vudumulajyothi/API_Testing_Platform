using System.Text;
using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using TestPilot.Application.Interfaces;

namespace TestPilot.Application.Services;

public class DocumentationExportService : IDocumentationExportService
{
    private readonly IApplicationDbContext _context;

    public DocumentationExportService(IApplicationDbContext context)
    {
        _context = context;
    }

    public async Task<string> ExportCollectionAsMarkdownAsync(Guid collectionId, Guid userId)
    {
        var collection = await _context.Collections
            .AsNoTracking()
            .Include(c => c.Requests)
                .ThenInclude(r => r.Headers)
            .Include(c => c.Requests)
                .ThenInclude(r => r.QueryParams)
            .Include(c => c.Requests)
                .ThenInclude(r => r.TestCases)
            .FirstOrDefaultAsync(c => c.CollectionId == collectionId && c.UserId == userId);

        if (collection == null)
        {
            throw new KeyNotFoundException($"Collection '{collectionId}' was not found or access is denied.");
        }

        var sb = new StringBuilder();
        sb.AppendLine($"# {collection.Name} – API Documentation");
        sb.AppendLine();
        if (!string.IsNullOrWhiteSpace(collection.Description))
        {
            sb.AppendLine($"> {collection.Description}");
            sb.AppendLine();
        }
        sb.AppendLine($"*Generated by TestPilot on {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC*");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        if (collection.Requests.Count == 0)
        {
            sb.AppendLine("*(No endpoints recorded in this collection)*");
            return sb.ToString();
        }

        foreach (var req in collection.Requests.OrderBy(r => r.Name))
        {
            sb.AppendLine($"### `{req.Method}` {req.Name}");
            sb.AppendLine($"**Endpoint URL:** `{req.Url}`");
            sb.AppendLine();

            // Headers
            if (req.Headers.Count > 0)
            {
                sb.AppendLine("#### Request Headers");
                sb.AppendLine("| Header | Value | Sensitive |");
                sb.AppendLine("|---|---|---|");
                foreach (var h in req.Headers)
                {
                    var val = h.IsSensitive ? "********" : h.HeaderValue;
                    sb.AppendLine($"| `{h.HeaderKey}` | `{val}` | {(h.IsSensitive ? "Yes" : "No")} |");
                }
                sb.AppendLine();
            }

            // Query Params
            if (req.QueryParams.Count > 0)
            {
                sb.AppendLine("#### Query Parameters");
                sb.AppendLine("| Parameter | Example Value |");
                sb.AppendLine("|---|---|");
                foreach (var p in req.QueryParams)
                {
                    sb.AppendLine($"| `{p.ParamKey}` | `{p.ParamValue}` |");
                }
                sb.AppendLine();
            }

            // Body
            if (!string.IsNullOrWhiteSpace(req.Body))
            {
                sb.AppendLine("#### Request Body");
                sb.AppendLine("```json");
                sb.AppendLine(req.Body);
                sb.AppendLine("```");
                sb.AppendLine();
            }

            // Test Assertions
            if (req.TestCases.Count > 0)
            {
                sb.AppendLine("#### Configured Assertions");
                sb.AppendLine("| Assertion Name | Type | Expected Value |");
                sb.AppendLine("|---|---|---|");
                foreach (var tc in req.TestCases)
                {
                    sb.AppendLine($"| {tc.Name} | `{tc.AssertionType}` | `{tc.ExpectedValue}` |");
                }
                sb.AppendLine();
            }

            sb.AppendLine("---");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    public async Task<string> ExportCollectionAsPostmanJsonAsync(Guid collectionId, Guid userId)
    {
        var collection = await _context.Collections
            .AsNoTracking()
            .Include(c => c.Requests)
                .ThenInclude(r => r.Headers)
            .Include(c => c.Requests)
                .ThenInclude(r => r.QueryParams)
            .FirstOrDefaultAsync(c => c.CollectionId == collectionId && c.UserId == userId);

        if (collection == null)
        {
            throw new KeyNotFoundException($"Collection '{collectionId}' was not found or access is denied.");
        }

        var postmanCollection = new
        {
            info = new
            {
                _postman_id = collection.CollectionId.ToString(),
                name = collection.Name,
                description = collection.Description ?? string.Empty,
                schema = "https://schema.getpostman.com/json/collection/v2.1.0/collection.json"
            },
            item = collection.Requests.Select(r => new
            {
                name = r.Name,
                request = new
                {
                    method = r.Method.ToString(),
                    header = r.Headers.Select(h => new
                    {
                        key = h.HeaderKey,
                        value = h.IsSensitive ? "********" : h.HeaderValue,
                        type = "text"
                    }),
                    body = string.IsNullOrWhiteSpace(r.Body) ? null : new
                    {
                        mode = "raw",
                        raw = r.Body,
                        options = new { raw = new { language = "json" } }
                    },
                    url = new
                    {
                        raw = r.Url,
                        query = r.QueryParams.Select(q => new
                        {
                            key = q.ParamKey,
                            value = q.ParamValue
                        })
                    }
                }
            })
        };

        return JsonSerializer.Serialize(postmanCollection, new JsonSerializerOptions { WriteIndented = true });
    }
}
